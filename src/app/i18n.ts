const tables = { en, fr };

/** Every message key, so tests can compare the two tables. */
export const MESSAGE_KEYS = Object.keys(en) as MessageKey[];

export function translate(lang: 'fr' | 'en', key: MessageKey, vars?: Record<string, string | number>): string {
  let text = tables[lang][key];
  if (vars) for (const [name, value] of Object.entries(vars)) text = text.replaceAll(`{${name}}`, String(value));
  return text;
}

export function useT() {
  const lang = useSettings((s) => s.lang);
  return (key: MessageKey, vars?: Record<string, string | number>) => translate(lang, key, vars);
}

export function errorKey(code: string): MessageKey {
  const key = `error.${code}`;
  return key in en ? (key as MessageKey) : 'error.generic';
}
